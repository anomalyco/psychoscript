#!/usr/bin/env bash
# Builds the PsychoScript Swift package (macOS with Xcode):
#
#   rust/crates/psychoscript-mobile/scripts/build-ios.sh [out-dir]   (default: rust/target/mobile/ios)
#
# Needs `rustup target add aarch64-apple-ios aarch64-apple-ios-sim aarch64-apple-darwin` for the
# toolchain in rust/rust-toolchain.toml. FEATURES=--no-default-features leaves out GPU canvases.
# Writes <out>/PsychoScript/, a local Swift package an app adds by path:
#   Package.swift
#   PsychoScriptFFI.xcframework          static libraries + C header (iOS, iOS Simulator, macOS; arm64)
#   Sources/PsychoScript/*.swift          one file per crate with UniFFI exports
# and <out>/REVISION, the commit it was built from.
#
# A host's own library that links psychoscript-mobile and adds UniFFI exports of its own builds the same package
# from its workspace: CRATE=<its package> (with a `cli` feature and the two `uniffi-bindgen*` binaries, as here)
# ROOT=<its Cargo workspace> REPO=<its repository's name, for REVISION> README=<its README>.
set -euo pipefail

crate="$(cd "$(dirname "$0")/.." && pwd)"
root="$(cd "${ROOT:-$crate/../..}" && pwd)"
package="${CRATE:-psychoscript-mobile}"
lib="lib${package//-/_}.a"
out="${1:-$root/target/mobile/ios}"
profile="${PROFILE:-release}"
features="${FEATURES:-}"
targets=(aarch64-apple-ios aarch64-apple-ios-sim aarch64-apple-darwin)
pkg="$out/PsychoScript"
target="${CARGO_TARGET_DIR:-$root/target}"

cd "$root"
# The vendored wgpu-hal's Metal fence tests (`vendor/wgpu-hal.patch`; logic only, no GPU work), before shipping it.
if [ -d vendor/wgpu-hal ]; then
  cargo test -q --manifest-path vendor/wgpu-hal/Cargo.toml --features metal --lib --target-dir "$target" -- metal::fence_tests
fi
export IPHONEOS_DEPLOYMENT_TARGET="${IPHONEOS_DEPLOYMENT_TARGET:-15.0}"
export MACOSX_DEPLOYMENT_TARGET="${MACOSX_DEPLOYMENT_TARGET:-13.0}"
for triple in "${targets[@]}"; do
  # shellcheck disable=SC2086
  cargo rustc -p "$package" --lib --profile "$profile" --target "$triple" --crate-type staticlib $features
done

gen="$target/mobile-gen/swift"
rm -rf "$gen" "$pkg"
mkdir -p "$gen/include" "$pkg/Sources/PsychoScript"
bindgen=(cargo run -q -p "$package" --features cli --bin uniffi-bindgen-swift --)
"${bindgen[@]}" "$target/aarch64-apple-ios/$profile/$lib" "$gen" --swift-sources
# A plain (not `framework`) module: the xcframework holds static libraries with their headers.
"${bindgen[@]}" "$target/aarch64-apple-ios/$profile/$lib" "$gen/include" --headers --modulemap \
  --module-name PsychoScriptFFI --modulemap-filename module.modulemap
# One Swift module for every crate's bindings (each crate's uniffi.toml names it `PsychoScript`).
cp "$gen"/*.swift "$pkg/Sources/PsychoScript/"
cat > "$pkg/Sources/PsychoScript/ErrorMessages.swift" <<'SWIFT'
// Generated by rust/crates/psychoscript-mobile/scripts/build-ios.sh.
public extension PsychoScriptError {
    /// The error's message, as the language gives it.
    var reason: String {
        switch self {
        case let .Syntax(_, reason, _, _), let .Runtime(_, reason, _, _): return reason
        case let .Timeout(reason, _), let .OutputTooLarge(reason, _), let .MemoryLimitExceeded(reason, _): return reason
        case let .InvalidInput(reason), let .Snapshot(reason), let .InvalidState(reason): return reason
        case let .SliceBudget(reason, _): return reason
        }
    }
}
SWIFT
if grep -q "enum GpuFailure" "$pkg"/Sources/PsychoScript/*.swift; then
  cat >> "$pkg/Sources/PsychoScript/ErrorMessages.swift" <<'SWIFT'

public extension GpuFailure {
    /// The failure's message.
    var reason: String {
        switch self {
        case let .Program(reason), let .Client(reason): return reason
        }
    }
}
SWIFT
  cat > "$pkg/Sources/PsychoScript/GpuSurface.swift" <<'SWIFT'
// Generated by rust/crates/psychoscript-mobile/scripts/build-ios.sh.
import QuartzCore

public extension GpuSurface {
    /// A surface presenting into `layer`, retained until the surface is dropped.
    static func metal(_ layer: CAMetalLayer) throws -> GpuSurface {
        try GpuSurface.metalLayer(pointer: UInt64(UInt(bitPattern: Unmanaged.passUnretained(layer).toOpaque())))
    }
}
SWIFT
fi

args=()
for triple in "${targets[@]}"; do
  args+=(-library "$target/$triple/$profile/$lib" -headers "$gen/include")
done
xcodebuild -create-xcframework "${args[@]}" -output "$pkg/PsychoScriptFFI.xcframework" >/dev/null

cat > "$pkg/Package.swift" <<'SWIFT'
// swift-tools-version:5.9
// Generated by anomalyco/psychoscript's rust/crates/psychoscript-mobile/scripts/build-ios.sh.
import PackageDescription

let package = Package(
    name: "PsychoScript",
    platforms: [.iOS(.v15), .macOS(.v13)],
    products: [.library(name: "PsychoScript", targets: ["PsychoScript"])],
    targets: [
        .binaryTarget(name: "PsychoScriptFFI", path: "PsychoScriptFFI.xcframework"),
        // What the static library links (`--print native-static-libs`): wgpu's Metal backend needs these.
        .target(
            name: "PsychoScript", dependencies: ["PsychoScriptFFI"], path: "Sources/PsychoScript",
            linkerSettings: [
                .linkedFramework("Metal"), .linkedFramework("QuartzCore"), .linkedFramework("CoreGraphics"),
                .linkedFramework("Foundation"), .linkedFramework("CoreFoundation"),
                .linkedLibrary("objc"), .linkedLibrary("iconv"),
            ]
        ),
    ]
)
SWIFT
cp "${README:-$crate/README.md}" "$out/"
echo "${REPO:-anomalyco/psychoscript} $(git -C "$root" rev-parse HEAD)$(git -C "$root" diff --quiet HEAD || echo " (modified)")" > "$out/REVISION"
ls -l "$target/aarch64-apple-ios/$profile/$lib"
du -sh "$pkg/PsychoScriptFFI.xcframework"/*
