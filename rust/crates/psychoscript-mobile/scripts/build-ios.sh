#!/usr/bin/env bash
# Builds the PsychoScript Swift package (macOS with Xcode):
#
#   rust/crates/psychoscript-mobile/scripts/build-ios.sh [out-dir]   (default: rust/target/mobile/ios)
#
# Needs `rustup target add aarch64-apple-ios aarch64-apple-ios-sim aarch64-apple-darwin` for the
# toolchain in rust/rust-toolchain.toml. FEATURES=--no-default-features leaves out `translateWgsl`.
# Writes <out>/PsychoScript/, a local Swift package an app adds by path:
#   Package.swift
#   PsychoScriptFFI.xcframework          static libraries + C header (iOS, iOS Simulator, macOS; arm64)
#   Sources/PsychoScript/*.swift
# and <out>/REVISION, the commit it was built from.
set -euo pipefail

crate="$(cd "$(dirname "$0")/.." && pwd)"
root="$(cd "$crate/../.." && pwd)"
out="${1:-$root/target/mobile/ios}"
profile="${PROFILE:-release}"
features="${FEATURES:-}"
targets=(aarch64-apple-ios aarch64-apple-ios-sim aarch64-apple-darwin)
pkg="$out/PsychoScript"

cd "$root"
export IPHONEOS_DEPLOYMENT_TARGET="${IPHONEOS_DEPLOYMENT_TARGET:-15.0}"
export MACOSX_DEPLOYMENT_TARGET="${MACOSX_DEPLOYMENT_TARGET:-13.0}"
for triple in "${targets[@]}"; do
  # shellcheck disable=SC2086
  cargo rustc -p psychoscript-mobile --lib --profile "$profile" --target "$triple" --crate-type staticlib $features
done

gen="$root/target/mobile-gen/swift"
rm -rf "$gen" "$pkg"
mkdir -p "$gen/include" "$pkg/Sources/PsychoScript"
lib="target/aarch64-apple-ios/$profile/libpsychoscript_mobile.a"
bindgen=(cargo run -q -p psychoscript-mobile --features cli --bin uniffi-bindgen-swift --)
"${bindgen[@]}" "$lib" "$gen" --swift-sources
# A plain (not `framework`) module: the xcframework holds static libraries with their headers.
"${bindgen[@]}" "$lib" "$gen/include" --headers --modulemap \
  --module-name PsychoScriptFFI --modulemap-filename module.modulemap
cp "$gen"/*.swift "$pkg/Sources/PsychoScript/PsychoScript.swift"
cat > "$pkg/Sources/PsychoScript/ErrorMessages.swift" <<'SWIFT'
// Generated by rust/crates/psychoscript-mobile/scripts/build-ios.sh.
public extension PsychoScriptError {
    /// The error's message, as the language gives it.
    var reason: String {
        switch self {
        case let .Syntax(_, reason, _, _), let .Runtime(_, reason, _, _): return reason
        case let .Timeout(reason, _), let .OutputTooLarge(reason, _), let .MemoryLimitExceeded(reason, _): return reason
        case let .InvalidInput(reason), let .Snapshot(reason), let .InvalidState(reason): return reason
        case let .SliceBudget(reason, _): return reason
        }
    }
}
SWIFT
if grep -q "enum ShaderError" "$pkg/Sources/PsychoScript/PsychoScript.swift"; then
  cat >> "$pkg/Sources/PsychoScript/ErrorMessages.swift" <<'SWIFT'

public extension ShaderError {
    /// The error's message, with its line and column when it has them.
    var reason: String {
        switch self {
        case let .Parse(reason, line?, column?), let .Validation(reason, line?, column?):
            return "\(reason) (line \(line), column \(column))"
        case let .Parse(reason, _, _), let .Validation(reason, _, _): return reason
        case let .Unsupported(reason), let .Translation(reason): return reason
        }
    }
}
SWIFT
fi

args=()
for triple in "${targets[@]}"; do
  args+=(-library "target/$triple/$profile/libpsychoscript_mobile.a" -headers "$gen/include")
done
xcodebuild -create-xcframework "${args[@]}" -output "$pkg/PsychoScriptFFI.xcframework" >/dev/null

cat > "$pkg/Package.swift" <<'SWIFT'
// swift-tools-version:5.9
// Generated by rust/crates/psychoscript-mobile/scripts/build-ios.sh in anomalyco/psychoscript.
import PackageDescription

let package = Package(
    name: "PsychoScript",
    platforms: [.iOS(.v15), .macOS(.v13)],
    products: [.library(name: "PsychoScript", targets: ["PsychoScript"])],
    targets: [
        .binaryTarget(name: "PsychoScriptFFI", path: "PsychoScriptFFI.xcframework"),
        .target(name: "PsychoScript", dependencies: ["PsychoScriptFFI"], path: "Sources/PsychoScript"),
    ]
)
SWIFT
cp "$crate/README.md" "$out/"
echo "anomalyco/psychoscript $(git -C "$root" rev-parse HEAD)$(git -C "$root" diff --quiet HEAD || echo " (modified)")" > "$out/REVISION"
ls -l target/aarch64-apple-ios/"$profile"/libpsychoscript_mobile.a
du -sh "$pkg/PsychoScriptFFI.xcframework"/*
