#!/usr/bin/env bash
# Builds the PsychoScript Android libraries and Kotlin bindings:
#
#   rust/crates/psychoscript-mobile/scripts/build-android.sh [out-dir]   (default: rust/target/mobile/android)
#
# Needs ANDROID_NDK_HOME (NDK r28 or later: 16 KB page-aligned), `cargo install cargo-ndk`, and
# `rustup target add aarch64-linux-android x86_64-linux-android` for the toolchain in
# rust/rust-toolchain.toml. FEATURES=--no-default-features leaves out GPU canvases. Writes
#   <out>/jniLibs/{arm64-v8a,x86_64}/libpsychoscript_mobile.so      stripped, for src/main/jniLibs
#   <out>/kotlin/com/anomalyco/psychoscript/psychoscript_mobile.kt   JNA bindings
#   <out>/kotlin/com/anomalyco/psychoscript/PsychoScriptGpu.kt       GPU surfaces from `android.view.Surface`s
#   <out>/kotlin/com/anomalyco/psychoscript/LiveFrames.kt            a live run's frames without JSON (one JNI call)
#   <out>/REVISION                                                    the commit it was built from
#
# A host's own library that links psychoscript-mobile and adds UniFFI exports of its own builds the same from its
# workspace: CRATE=<its package> (with a `cli` feature and the `uniffi-bindgen` binary, as here) ROOT=<its Cargo
# workspace> REPO=<its repository's name, for REVISION> README=<its README>. The library is then lib<its lib>.so, and
# the bindings of its own exports are written beside these, in the package its uniffi.toml names.
set -euo pipefail

crate="$(cd "$(dirname "$0")/.." && pwd)"
root="$(cd "${ROOT:-$crate/../..}" && pwd)"
package="${CRATE:-psychoscript-mobile}"
name="${package//-/_}"
target="${CARGO_TARGET_DIR:-$root/target}"
out="${1:-$root/target/mobile/android}"
profile="${PROFILE:-release}"
api="${ANDROID_API:-21}"
features="${FEATURES:-}"
: "${ANDROID_NDK_HOME:?set ANDROID_NDK_HOME to an Android NDK}"

strip="$(ls "$ANDROID_NDK_HOME"/toolchains/llvm/prebuilt/*/bin/llvm-strip | head -n 1)"
cd "$root"
rm -rf "$out"
mkdir -p "$out/kotlin"

for abi in arm64-v8a:aarch64-linux-android x86_64:x86_64-linux-android; do
  abi_name="${abi%%:*}"
  triple="${abi#*:}"
  # shellcheck disable=SC2086
  cargo ndk -t "$abi_name" -P "$api" rustc -p "$package" --lib --profile "$profile" --crate-type cdylib $features
  mkdir -p "$out/jniLibs/$abi_name"
  cp "$target/$triple/$profile/lib$name.so" "$out/jniLibs/$abi_name/"
done

# Bindings from the unstripped library (its UniFFI metadata), then strip.
cargo run -q -p "$package" --features cli --bin uniffi-bindgen -- generate \
  --library "$target/aarch64-linux-android/$profile/lib$name.so" \
  --language kotlin --out-dir "$out/kotlin" --no-format
if grep -q "class GpuSurface" "$out/kotlin/com/anomalyco/psychoscript/psychoscript_mobile.kt"; then
  sed "s/@LIB@/$name/" > "$out/kotlin/com/anomalyco/psychoscript/PsychoScriptGpu.kt" <<'KOTLIN'
// Generated by rust/crates/psychoscript-mobile/scripts/build-android.sh.
package com.anomalyco.psychoscript

import android.view.Surface

/** GPU surfaces from Android views (README: GPU canvases). */
object PsychoScriptGpu {
    init {
        System.loadLibrary("@LIB@")
    }

    /**
     * A [GpuSurface] presenting into [surface] (a `SurfaceView`'s `holder.surface`, or a `Surface` of a
     * `SurfaceTexture`). It holds the surface's `ANativeWindow` until it is dropped (`close()`).
     */
    fun surface(surface: Surface): GpuSurface {
        val window = nativeWindow(surface)
        require(window != 0L) { "not a valid Surface" }
        return GpuSurface.androidWindow(window.toULong())
    }

    private external fun nativeWindow(surface: Surface): Long
}
KOTLIN
fi
if grep -q "class LiveRun" "$out/kotlin/com/anomalyco/psychoscript/psychoscript_mobile.kt"; then
  sed "s/@LIB@/$name/" > "$out/kotlin/com/anomalyco/psychoscript/LiveFrames.kt" <<'KOTLIN'
// Generated by rust/crates/psychoscript-mobile/scripts/build-android.sh.
package com.anomalyco.psychoscript

/**
 * A live run's frames without JSON (README: Live runs): [deliver] queues the message `run.deliver(json)` would
 * for `{"type":"frame","frame":{"t","dt","width","height","scale","pointer","dark","fullscreen","close"}}`, in the
 * same order with the run's other messages, through one JNI call with no string, no allocation and no UniFFI call.
 * It holds a reference to the run of its own, taken once: [close] it when the run ends.
 */
class LiveFrames(run: LiveRun) : AutoCloseable {
    private var run: Long = run.callWithHandle { adopt(it) }

    /**
     * Queues a frame: [pointer] the pointer `{ x, y, down }` or none (`null`), [close] the close area
     * `{ x, y, width, height }` or none. Throws [PsychoScriptException.InvalidState] once the run ended, as
     * `run.deliver` does, and after [close].
     */
    @Synchronized
    fun deliver(
        t: Double, dt: Double, width: Float, height: Float, scale: Float,
        pointer: Boolean, pointerX: Float, pointerY: Float, pointerDown: Boolean,
        dark: Boolean, fullscreen: Boolean,
        close: Boolean, closeX: Double, closeY: Double, closeWidth: Double, closeHeight: Double,
    ) {
        val sent = run != 0L && send(
            run, t, dt, width.toDouble(), height.toDouble(), scale.toDouble(),
            pointer, pointerX.toDouble(), pointerY.toDouble(), pointerDown, dark, fullscreen,
            close, closeX, closeY, closeWidth, closeHeight,
        ) == 0
        if (!sent) throw PsychoScriptException.InvalidState("the run has ended")
    }

    /** Lets go of the run; [deliver] throws from then on. */
    @Synchronized
    override fun close() {
        if (run != 0L) free(run)
        run = 0L
    }

    private companion object {
        init {
            System.loadLibrary("@LIB@")
        }

        @JvmStatic private external fun adopt(handle: Long): Long

        @JvmStatic private external fun send(
            run: Long, t: Double, dt: Double, width: Double, height: Double, scale: Double,
            pointer: Boolean, pointerX: Double, pointerY: Double, pointerDown: Boolean,
            dark: Boolean, fullscreen: Boolean,
            close: Boolean, closeX: Double, closeY: Double, closeWidth: Double, closeHeight: Double,
        ): Int

        @JvmStatic private external fun free(run: Long)
    }
}
KOTLIN
fi
for so in "$out"/jniLibs/*/lib"$name".so; do
  "$strip" --strip-unneeded "$so"
done
cp "${README:-$crate/README.md}" "$out/"
echo "${REPO:-anomalyco/psychoscript} $(git -C "$root" rev-parse HEAD)$(git -C "$root" diff --quiet HEAD || echo " (modified)")" > "$out/REVISION"
ls -l "$out"/jniLibs/*/
